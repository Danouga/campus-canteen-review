import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import mysql from 'mysql2/promise';
import { connectDatabase } from '../db.mjs';
import { createAuthService, normalizeEmail } from '../auth.mjs';
import { createAppServer } from '../server-core.mjs';

const local = Object.fromEntries((await readFile(new URL('../.env.local', import.meta.url), 'utf8')).split(/\r?\n/).map((line) => line.match(/^([A-Z_]+)=(.*)$/)).filter(Boolean).map((match) => [match[1], match[2]]));
const name = `canteen_auth_test_${randomBytes(4).toString('hex')}`;
const config = { ...local, DB_HOST: '127.0.0.1', DB_PORT: 3306, DB_NAME: name };
const control = await mysql.createConnection({ host: config.DB_HOST, port: 3306, user: config.DB_USER || 'root', password: config.DB_PASSWORD || '' });
let db, server;
try {
  db = await connectDatabase(config);
  let time = Date.now();
  const mails = new Map();
  const auth = createAuthService({ store: db.authStore, config, now: () => time, mailer: { ready: true, async sendCode(email, code) { mails.set(email, code); } } });
  server = createAppServer({ database: db, config, auth });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  async function request(path, body, cookie = '') {
    const response = await fetch(base + path, { method: body ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json', Cookie: cookie, Origin: base }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json(), cookie: response.headers.get('set-cookie')?.split(';')[0] || '', headers: response.headers };
  }
  assert.equal(normalizeEmail(' A@Example.com '), 'a@example.com');
  assert.throws(() => normalizeEmail('a..b@example.com'));
  const send = await request('/api/auth/send-code', { email: 'member@example.com', purpose: 'register' });
  assert.equal(send.status, 200);
  assert.equal('code' in send.body, false);
  assert.equal((await request('/api/auth/send-code', { email: 'member@example.com', purpose: 'register' })).status, 429);
  const input = { email: 'member@example.com', challengeId: send.body.challengeId, code: mails.get('member@example.com'), name: '测试用户', role: 'admin', password: 'Test!Password234', confirmPassword: 'Test!Password234' };
  const simultaneous = await Promise.all([request('/api/auth/register', input), request('/api/auth/register', input)]);
  assert.equal(simultaneous.filter((r) => r.status === 200).length, 1);
  const login = simultaneous.find((r) => r.status === 200);
  assert.equal(login.body.user.role, 'member');
  assert.match(login.headers.get('set-cookie'), /HttpOnly; SameSite=Lax/);
  assert.equal((await request('/api/auth/me', null, login.cookie)).body.user.id, login.body.user.id);
  assert.equal((await request('/api/action', { method: 'saveCampus', args: ['campus-a', '伪造', 'demo-admin'] }, login.cookie)).status, 403);
  assert.equal((await request('/api/action', { method: 'reviewContribution', args: ['fake', 'fixed', '', 'demo-admin'] }, login.cookie)).status, 403);
  assert.equal((await request('/api/action', { method: 'submitPost', args: [{ actorId: 'demo-admin' }] })).status, 401);
  assert.equal((await request('/api/action', { method: 'expireProvisional', args: [] })).status, 200);
  await db.action('saveCanteen', [{ campusId: 'campus-a', name: '食堂', actorId: 'demo-admin' }]);
  const canteen = (await db.snapshot()).canteens[0];
  await db.action('saveShop', [{ canteenId: canteen.id, name: '店铺', actorId: 'demo-admin' }]);
  const shop = (await db.snapshot()).shops[0];
  const posted = await request('/api/action', { method: 'addComment', args: ['shop', shop.id, 'demo-admin', '好吃'] }, login.cookie);
  assert.equal(posted.status, 200);
  assert.equal((await db.snapshot()).comments[0].ownerId, login.body.user.id);
  assert.equal((await request('/api/action', { method: 'castRecommendationVote', args: [shop.id, 'demo-admin'] }, login.cookie)).status, 200);
  const publicState = (await request('/api/state')).body.data;
  assert.equal(publicState.recommendationVotes.length, 0);
  assert.equal(publicState.weeklyVoteCounts[0].count, 1);
  assert.equal(JSON.stringify(publicState).includes('member@example.com'), false);
  assert.equal((await request('/api/auth/logout', {}, login.cookie)).status, 200);
  assert.equal((await request('/api/auth/me', null, login.cookie)).body.user, null);
  time += 61_000;
  const retry = await auth.send({ email: 'member@example.com', purpose: 'reset-password' }, 'another-ip');
  const good = mails.get('member@example.com');
  const bad = good === '000000' ? '000001' : '000000';
  for (let i = 0; i < 5; i++) await assert.rejects(auth.complete({ email: 'member@example.com', challengeId: retry.challengeId, code: bad, password: 'Test!NewPassword234', confirmPassword: 'Test!NewPassword234' }, 'another-ip', 'reset-password'));
  await assert.rejects(auth.complete({ email: 'member@example.com', challengeId: retry.challengeId, code: good, password: 'Test!NewPassword234', confirmPassword: 'Test!NewPassword234' }, 'another-ip', 'reset-password'));
  time += 61_000;
  const expiring = await auth.send({ email: 'expire@example.com', purpose: 'register' }, 'expiry-ip');
  time += 600_001;
  await assert.rejects(auth.complete({ email: 'expire@example.com', challengeId: expiring.challengeId, code: mails.get('expire@example.com'), password: 'Test!Password234', confirmPassword: 'Test!Password234' }, 'expiry-ip', 'register'));
  // Password login works without a new verification email.
  const passwordLogin = await request('/api/auth/login', { email: input.email, password: input.password });
  assert.equal(passwordLogin.status, 200);
  assert.equal((await request('/api/auth/login', { email: input.email, password: 'wrong-password' })).status, 401);
  assert.equal((await request('/api/auth/verify-code', input)).status, 404);
  const [[stored]] = await control.execute(`SELECT password_hash FROM \`${name}\`.auth_users WHERE email = ?`, [input.email]);
  assert.match(stored.password_hash, /^scrypt\$/);
  assert.equal(stored.password_hash.includes(input.password), false);
  const reset = await request('/api/auth/send-code', { email: input.email, purpose: 'reset-password' });
  const resetInput = { email: input.email, code: mails.get(input.email), challengeId: reset.body.challengeId, password: 'Test!NewPassword234', confirmPassword: 'Test!NewPassword234' };
  // A reset challenge cannot register or change a password under a different purpose.
  assert.equal((await request('/api/auth/register', resetInput)).status, 400);
  assert.equal((await request('/api/auth/reset-password', { ...resetInput, confirmPassword: 'mismatch' })).status, 400);
  assert.equal((await request('/api/auth/reset-password', resetInput)).status, 200);
  assert.equal((await request('/api/auth/me', null, passwordLogin.cookie)).body.user, null);
  assert.equal((await request('/api/auth/login', { email: input.email, password: input.password })).status, 401);
  const newLogin = await request('/api/auth/login', { email: input.email, password: resetInput.password });
  assert.equal(newLogin.status, 200);
  assert.equal((await request('/api/auth/reset-password', resetInput)).status, 400);
  assert.equal((await request('/api/auth/send-code', { email: input.email, purpose: 'change-password' })).status, 401);
  time += 61_000;
  const change = await request('/api/auth/send-code', { email: 'forged@example.com', purpose: 'change-password' }, newLogin.cookie);
  assert.equal(change.status, 200);
  const changed = await request('/api/auth/change-password', { email: 'forged@example.com', challengeId: change.body.challengeId, code: mails.get(input.email), password: 'Test!Changed234', confirmPassword: 'Test!Changed234' }, newLogin.cookie);
  assert.equal(changed.status, 200);
  assert.equal((await request('/api/auth/me', null, newLogin.cookie)).body.user, null);
  assert.equal((await request('/api/auth/login', { email: input.email, password: 'Test!Changed234' })).status, 200);
  // Old manually provisioned admins gain a password through recovery, preserving role.
  await control.execute(`INSERT INTO \`${name}\`.auth_users (id, email, name, role, verified_at) VALUES (UUID(), 'admin@example.com', '管理员', 'admin', NOW())`);
  const adminCode = await request('/api/auth/send-code', { email: 'admin@example.com', purpose: 'reset-password' });
  assert.equal((await request('/api/auth/reset-password', { email: 'admin@example.com', challengeId: adminCode.body.challengeId, code: mails.get('admin@example.com'), password: 'Test!Admin234', confirmPassword: 'Test!Admin234' })).status, 200);
  const adminLogin = await request('/api/auth/login', { email: 'admin@example.com', password: 'Test!Admin234' });
  assert.equal(adminLogin.body.user.role, 'admin');
  assert.equal((await request('/api/action', { method: 'saveCampus', args: ['campus-a', '管理员设置校区', 'demo-admin'] }, adminLogin.cookie)).status, 200);
  const unknownCode = await request('/api/auth/send-code', { email: 'missing@example.com', purpose: 'reset-password' });
  assert.equal((await request('/api/auth/reset-password', { email: 'missing@example.com', challengeId: unknownCode.body.challengeId, code: mails.get('missing@example.com'), password: 'Test!Missing234', confirmPassword: 'Test!Missing234' })).status, 400);
  assert.equal(await db.authStore.passwordAccount('missing@example.com'), null);
  time += 61_000;
  const duplicateCode = await request('/api/auth/send-code', { email: input.email, purpose: 'register' });
  assert.equal((await request('/api/auth/register', { ...input, challengeId: duplicateCode.body.challengeId, code: mails.get(input.email) })).status, 400);
  assert.equal((await request('/api/auth/login', { email: input.email, password: 'Test!Changed234' })).status, 200);
  await control.execute(`UPDATE \`${name}\`.auth_users SET status = 'blocked' WHERE email = 'admin@example.com'`);
  assert.equal((await request('/api/auth/me', null, adminLogin.cookie)).body.user, null);
  assert.equal((await request('/api/auth/login', { email: 'admin@example.com', password: 'Test!Admin234' })).status, 401);
  console.log('账户系统：验证码注册、密码登录、密码哈希、找回与修改密码、用途隔离、全会话撤销、已有管理员首次设置密码、并发一次性校验、权限与票据隐私均通过（未发送真实邮件）。');
} finally {
  if (server) await new Promise((resolve) => server.close(resolve));
  await db?.close();
  await control.query(`DROP DATABASE IF EXISTS \`${name}\``);
  await control.end();
}
